// Reassembles docs/verification-log.md from the per-entry files under
// docs/verification-log/index/. This is a pure concatenation (no
// reformatting) so the assembled file is byte-identical to hand-editing the
// monolith directly, except that appends now touch a NEW file under
// docs/verification-log/index/ instead of the shared docs/verification-log.md
// tail -- see docs/verification-log/index/README.md for why (contention
// decomposition, no DEC yet).
//
// Usage:
//   tsx scripts/assemble-verification-log.ts            # rewrite docs/verification-log.md
//   tsx scripts/assemble-verification-log.ts --check     # exit 1 if out of date (CI use)
//   tsx scripts/assemble-verification-log.ts --next-seq  # print next 4-digit sequence prefix

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const INDEX_DIR = join(ROOT, "docs", "verification-log", "index");
const OUTPUT_FILE = join(ROOT, "docs", "verification-log.md");

const PREAMBLE = `# Verification Log
Append-only. One dated section per run.

Per-run full detail lives under \`docs/verification-log/<file>.md\` (one file
per section below, extracted to reduce merge contention on this file — see
DEC-068/DEC-069). Each section here keeps the exact \`## <date> <branch> —
<scope> @ <sha>\` header and, where applicable, the closing \`RESULT:\` /
\`OPEN ITEMS:\` line verbatim, so this file alone remains sufficient for the
DEC-069 exit-predicate grep.

This file is generated by \`tsx scripts/assemble-verification-log.ts\` from
the per-run entry files under \`docs/verification-log/index/\` (sequence-
numbered, one file per section, in append order). Do not hand-edit the
sections below -- add a new file under \`docs/verification-log/index/\` and
re-run the assembler. This split exists purely to stop concurrent branches
from all editing the same file tail; the assembled output is unchanged.
`;

function entryFiles(): string[] {
  return readdirSync(INDEX_DIR)
    .filter((f) => /^\d{4}-.*\.md$/.test(f))
    .sort();
}

// DEC-068 wave-37 amendment: nextSeq() mints one past the HIGHEST existing
// prefix, so every concurrent lane in a wave gets the same number by
// construction -- wave 35's merge train hand-renumbered a silent 0188
// collision and no test caught it. Detection belongs in the instrument:
// both --check and the default write path call this and fail loudly on any
// duplicate 4-digit prefix, naming every colliding file.
export function duplicateSequences(files: readonly string[]): string[] {
  const byPrefix = new Map<string, string[]>();
  for (const f of files) {
    const prefix = f.slice(0, 4);
    const existing = byPrefix.get(prefix);
    if (existing) {
      existing.push(f);
    } else {
      byPrefix.set(prefix, [f]);
    }
  }
  const collisions: string[] = [];
  for (const group of byPrefix.values()) {
    if (group.length > 1) {
      collisions.push(...group);
    }
  }
  return collisions.sort();
}

function assertNoDuplicateSequences(files: readonly string[]): void {
  const collisions = duplicateSequences(files);
  if (collisions.length > 0) {
    throw new Error(
      `assemble-verification-log: duplicate 4-digit sequence prefix among: ${collisions.join(
        ", ",
      )} -- nextSeq() mints one past the highest prefix, so concurrent lanes in one wave collide by construction (DEC-068 wave-37 amendment). Remediation: renumber every file but the earliest-dated one in each colliding group to the next free sequence(s), then re-run \`tsx scripts/assemble-verification-log.ts\`.`,
    );
  }
}

function assemble(): string {
  const files = entryFiles();
  assertNoDuplicateSequences(files);
  const parts = [PREAMBLE];
  for (const f of files) {
    parts.push(readFileSync(join(INDEX_DIR, f), "utf8"));
  }
  return parts.join("");
}

function nextSeq(): string {
  const files = entryFiles();
  const last = files.length > 0 ? files[files.length - 1] : undefined;
  const lastNum = last ? Number.parseInt(last.slice(0, 4), 10) : 0;
  return String(lastNum + 1).padStart(4, "0");
}

// Guarded so this module can be imported for its pure exports (e.g.
// duplicateSequences) -- by tests -- without triggering a filesystem write
// or process.exit as a side effect of import (matches
// scripts/ensure-dev-vars.ts / scripts/exit-predicate.ts's thin-CLI shape).
if (import.meta.url === `file://${process.argv[1]}`) {
  const mode = process.argv[2];

  if (mode === "--next-seq") {
    process.stdout.write(nextSeq() + "\n");
  } else if (mode === "--check") {
    const current = readFileSync(OUTPUT_FILE, "utf8");
    const expected = assemble();
    if (current !== expected) {
      console.error(
        "docs/verification-log.md is out of date with docs/verification-log/index/*.md -- run `tsx scripts/assemble-verification-log.ts`",
      );
      process.exit(1);
    }
    console.log("docs/verification-log.md is up to date.");
  } else {
    writeFileSync(OUTPUT_FILE, assemble());
    console.log(`Wrote ${OUTPUT_FILE} from ${entryFiles().length} entries.`);
  }
}
