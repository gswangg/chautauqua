// Every DEC_NNN constant declared across src/decisions-data/*.ts. Reuses the
// exact regex idiom from test/decisions-parity.test.ts:30 so the two guards
// never silently diverge on what counts as a declared constant.
function declaredDecConstants(): string[] {
  const constants: string[] = [];
  const files = readdirSync(decisionsDataDir).filter((name) => name.endsWith(".ts"));
  for (const file of files) {
    const contents = readFileSync(join(decisionsDataDir, file), "utf8");
    const matches = contents.matchAll(/^export const (DEC_\d+)\b/gm);
    for (const match of matches) {
      const name = match[1];
      if (name === undefined) throw new Error(`unexpected match with no capture group in ${file}`);
      constants.push(name);
    }
  }
  return constants;
}

// Deterministic recursive walk of a directory, collecting .ts/.tsx files.
// Never descends into node_modules or dist, and skips whatever the caller
// excludes (the decisions machinery itself).
function walkSourceFiles(dir: string, isExcluded: (fullPath: string) => boolean): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (isExcluded(full)) continue;
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (name === "node_modules" || name === "dist") continue;
      out.push(...walkSourceFiles(full, isExcluded));
    } else if (name.endsWith(".ts") || name.endsWith(".tsx")) {
      out.push(full);
    }
  }
  return out;
}

function isExcludedFromWalk(full: string): boolean {
  if (full.startsWith(decisionsDataDir + sep)) return true;
  if (full === decisionsJsSrcFile) return true;
  return false;
}

function directoryExists(path: string): boolean {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

// Which declared DEC_NNN identifiers appear (word-boundary, so DEC_04 never
// matches DEC_040) anywhere under src/ or app/src/, excluding the decisions
// machinery itself.
function referencedDecConstants(declared: string[]): Set<string> {
  const files = [
    ...walkSourceFiles(srcDir, isExcludedFromWalk),
    ...(directoryExists(appSrcDir) ? walkSourceFiles(appSrcDir, isExcludedFromWalk) : []),
  ];
  const referenced = new Set<string>();
  const remaining = new Set(declared);
  for (const file of files) {
    if (remaining.size === 0) break;
    const contents = readFileSync(file, "utf8");
    for (const id of [...remaining]) {
      const pattern = new RegExp(`\\b${id}\\b`);
      if (pattern.test(contents)) {
        referenced.add(id);
        remaining.delete(id);
      }
    }
  }
  return referenced;
}

